def deposit(money):
    balance = 1000.0  # ยอดเงินเริ่มต้น 1,000 บาท
    
    try:
        # แปลงข้อมูลรับเข้าเป็น float
        amount = float(money)
        
        # ตรวจสอบเงื่อนไขว่าต้องฝากมากกว่า 0 บาท
        if amount <= 0:
            raise ValueError("จำนวนเงินฝากต้องมากกว่า 0")
            
    except ValueError as e:
        # ดักจับทั้งกรณีพิมพ์ข้อความที่ไม่ใช่ตัวเลข และกรณีระบุเงิน <= 0
        if "could not convert" in str(e):
            print("\nเกิดข้อผิดพลาด: กรุณากรอกข้อมูลเป็นตัวเลขเท่านั้น")
        else:
            print(f"\nเกิดข้อผิดพลาด: {e}")
            
    else:
        # แสดงผลเมื่อไม่มีข้อผิดพลาด
        balance += amount
        print("\nฝากเงินสำเร็จ")
        print(f"ยอดเงินคงเหลือ: {balance:.2f} บาท")
        
    finally:
        # แสดงข้อความนี้เสมอ
        print("สิ้นสุดรายการฝากเงิน")


# --------------------------------------------------
# รับค่าจากผู้ใช้ผ่านคีย์บอร์ด (input) แล้วเรียกใช้ฟังก์ชัน
# --------------------------------------------------
print("ยอดเงินเริ่มต้น: 1000 บาท")
user_input = input("กรอกจำนวนเงินที่ต้องการฝาก: ")
deposit(user_input)